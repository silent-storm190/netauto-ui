"""Generate the shared browser formatter from the backend's canonical labels."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'components/get_info/drop_point_check/models.py'
TARGET = ROOT / 'mockup_ui/shared/customer-status.js'


def render():
    tree = ast.parse(SOURCE.read_text(encoding='utf-8'))
    labels = next(ast.literal_eval(node.value) for node in tree.body
                  if isinstance(node, ast.Assign)
                  and any(isinstance(t, ast.Name) and t.id == 'CONTRACT_STATUS_LABELS'
                          for t in node.targets))
    catalog = json.dumps(labels, ensure_ascii=False, separators=(',', ':'))
    return '''/* Generated by scripts/generate-customer-status.py. Do not edit labels here. */
(function(root,factory){const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.NETAUTO_CUSTOMER_STATUS=api;})(typeof window==='object'?window:globalThis,function(){
  'use strict';
  const labels=CATALOG;
  function format(value){
    if(value==null||typeof value==='object')return null;
    const text=String(value).trim(),key=text.toLowerCase().replace(/\\s+/g,' ');
    if(['','none','null','n/a','-','—'].includes(key))return null;
    const label=Object.prototype.hasOwnProperty.call(labels,key)?labels[key]:text;
    return label==='Bình thường'?'Bình Thường':label;
  }
  return {format};
});
'''.replace('CATALOG', catalog)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit('Regenerate mockup_ui/shared/customer-status.js')
        print('Shared customer status labels match backend.')
    else:
        TARGET.write_text(expected, encoding='utf-8', newline='\n')
